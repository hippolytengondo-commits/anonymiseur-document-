"""Espaces ANONYX : tableau de bord, bilingue, coffre, historique, sécurité, mobile, hors ligne. Chrome + Playwright."""
import asyncio, os, sys, json, subprocess, time
from playwright.async_api import async_playwright
fails = []
def check(c, m):
    print(("OK   " if c else "FAIL ") + m)
    if not c: fails.append(m)
PW = "Phrase-test-1234"
TEXT = "Entre Alpha Conseil SARL, représentée par Monsieur Paul Dupont, et Beta Industries SA. Contact : contact@alpha-exemple.test."
PORT = 8777
srv = subprocess.Popen([sys.executable, "-m", "http.server", str(PORT), "--directory", "."], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
time.sleep(1)
URL = f"http://localhost:{PORT}/index.html"
async def new_page(b, errs, vp=None, locale="fr-FR"):
    ctx = await b.new_context(viewport=vp or {"width": 1280, "height": 800}, locale=locale)
    pg = await ctx.new_page()
    pg.on("pageerror", lambda e: errs.append("PAGEERR " + str(e)))
    pg.on("console", lambda m: errs.append("CONSOLE " + m.text) if m.type == "error" else None)
    return ctx, pg
async def go(pg, v):
    await pg.evaluate(f"location.hash='#/{v}'"); await pg.wait_for_selector(f".view[data-view='{v}']:not([hidden])")
async def process(pg, text=TEXT):
    await go(pg, "anonymize")
    await pg.evaluate("document.querySelector('#s1 details').open = true"); await pg.fill("#paste", text); await pg.click("#use-paste")
    await pg.click("#analyze"); await pg.wait_for_selector("#s3:not([hidden])")
    await pg.click("#run"); await pg.wait_for_selector("#s4:not([hidden])")
async def make_vault(pg):
    await pg.fill("#pp-pass", PW); await pg.fill("#pp-confirm", PW); await pg.click("#pp-ok")
    await pg.wait_for_selector("#pp-form", state="detached")
async def main():
    async with async_playwright() as p:
        b = await p.chromium.launch(executable_path=os.environ.get("CHROME", "/usr/bin/google-chrome"), args=["--no-sandbox"])
        errs = []
        # ---- A. Navigation, tableau de bord vide, aucune donnée inventée
        ctx, pg = await new_page(b, errs)
        await pg.goto(URL); await pg.wait_for_selector(".view:not([hidden])")
        check(await pg.locator("#nav a").count() == 9, "9 espaces dans le menu latéral")
        for v in ["dashboard", "anonymize", "restore", "documents", "vault", "activity", "security", "plans", "profile"]:
            await go(pg, v)
            check(await pg.locator(f".view[data-view='{v}'] h1").first.is_visible(), f"espace « {v} » affiché avec un titre")
        await go(pg, "dashboard")
        kp = (await pg.inner_text("#kpis")).replace("\n", " ")
        check(kp.startswith("Documents traités 0 Remplacements effectués 0 Tables dans le coffre 0"), "indicateurs à zéro, sans statistique inventée : " + kp)
        check("Non créé" in await pg.inner_text("#prot") and "Aucune" in await pg.inner_text("#prot"), "état de protection réel")
        check(await pg.evaluate("[...document.images].every(i => i.alt)"), "toutes les images ont un texte alternatif")
        check(await pg.evaluate("document.querySelectorAll('main').length === 1 && document.querySelectorAll('nav').length >= 1"), "repères d'accessibilité (main, nav)")
        # ---- B. Bilingue
        await pg.click(".side [data-lang='en']")
        check("Dashboard" in await pg.inner_text("#nav") and await pg.evaluate("document.documentElement.lang") == "en", "interface passée en anglais")
        check("Hello" in await pg.inner_text("#dash-hello"), "accueil en anglais")
        await process(pg)
        prev = await pg.inner_text("#preview")
        check("Company A" in prev and "Person A" in prev and "[EMAIL 1]" in prev, "désignations en anglais : " + prev[:80].replace("\n", " "))
        check("Pseudonymisation — reversible operation" in await pg.inner_text("#s4"), "avertissement en anglais")
        await pg.reload(); await pg.wait_for_selector(".view:not([hidden])")
        check(await pg.evaluate("document.documentElement.lang") == "en", "langue mémorisée après rechargement")
        await go(pg, "profile"); await pg.select_option("#pf-labels", "fr")
        await process(pg)
        check("Société A" in await pg.inner_text("#preview"), "langue des désignations indépendante de l'interface")
        await go(pg, "profile"); await pg.select_option("#pf-lang", "fr")
        check("Tableau de bord" in await pg.inner_text("#nav"), "retour au français")
        await ctx.close()
        # ---- C. Coffre chiffré, historique, documents, activités
        ctx, pg = await new_page(b, errs)
        await pg.goto(URL); await process(pg)
        await pg.click("#save-map")
        await pg.fill("#pp-pass", "court"); await pg.fill("#pp-confirm", "court"); await pg.click("#pp-ok")
        check("10 caractères" in await pg.inner_text("#pp-err"), "phrase trop courte refusée")
        await pg.fill("#pp-pass", PW); await pg.fill("#pp-confirm", PW + "x"); await pg.click("#pp-ok")
        check("ne correspondent pas" in await pg.inner_text("#pp-err"), "confirmation différente refusée")
        await pg.fill("#pp-confirm", PW); await pg.click("#pp-ok"); await pg.wait_for_selector("#pp-form", state="detached")
        check("coffre" in await pg.inner_text("#m4"), "table enregistrée")
        ls = await pg.evaluate("JSON.stringify(Object.entries(localStorage))")
        check(all(w not in ls for w in ["Alpha", "Dupont", "Beta Industries", "alpha-exemple"]), "aucune identité ni contenu en clair dans localStorage")
        vault = json.loads(await pg.evaluate("localStorage.getItem('anonyx_vault_v1')"))
        check(vault["iter"] >= 600000 and "ct" in vault["items"][0] and "entries" not in json.dumps(vault), "coffre chiffré (PBKDF2 ≥ 600 000, AES-GCM)")
        await go(pg, "dashboard")
        kp = (await pg.inner_text("#kpis")).replace("\n", " ")
        check("Documents traités 1" in kp and "Tables dans le coffre 1" in kp, "indicateurs réels : " + kp)
        check("Déverrouillé" in await pg.inner_text("#prot"), "état du coffre : déverrouillé")
        await go(pg, "documents")
        li = await pg.inner_text("#doc-list")
        check("Pseudonymisé — table dans le coffre" in li and "Alpha" not in li, "document listé sans nom de fichier : " + li.replace("\n", " ")[:90])
        await pg.select_option("#doc-status", "none")
        check("Aucun" in await pg.inner_text("#doc-list"), "filtre par statut")
        await pg.select_option("#doc-status", "all")
        await go(pg, "vault")
        check(await pg.locator(".vcard").count() == 1, "table visible dans Correspondances")
        await pg.click("[data-vt='reveal']")
        check("Alpha Conseil SARL" in await pg.inner_text(".vals"), "valeurs affichées à la demande")
        await pg.click("[data-vt='reveal']")
        check(await pg.locator(".vals").is_hidden(), "valeurs masquées de nouveau")
        await pg.click("[data-vt='lock']")
        check(await pg.locator("[data-vt='unlock']").count() == 1 and await pg.locator(".vcard").count() == 0, "coffre verrouillé : aucune table visible")
        await pg.click("[data-vt='unlock']"); await pg.fill("#pp-pass", "mauvaise-phrase-xx"); await pg.click("#pp-ok"); await pg.wait_for_selector("#pp-err.err")
        check("incorrecte" in await pg.inner_text("#pp-err"), "mauvaise phrase refusée")
        await pg.fill("#pp-pass", PW); await pg.click("#pp-ok"); await pg.wait_for_selector("#pp-form", state="detached")
        await pg.click("[data-vt='change']")
        await pg.fill("#pp-pass", PW); await pg.fill("#pp-new", PW + "-2"); await pg.fill("#pp-confirm", PW + "-2"); await pg.click("#pp-ok")
        await pg.wait_for_selector("#pp-form", state="detached")
        await pg.click("[data-vt='lock']"); await pg.click("[data-vt='unlock']")
        await pg.fill("#pp-pass", PW + "-2"); await pg.click("#pp-ok"); await pg.wait_for_selector("#pp-form", state="detached")
        check(await pg.locator(".vcard").count() == 1, "changement de phrase secrète : table conservée")
        await go(pg, "activity")
        act = await pg.inner_text("#act-list")
        check("Remplacements appliqués" in act and "Coffre créé" in act and "Alpha" not in act, "journal des activités sans contenu")
        # verrouillage automatique
        await pg.evaluate("vaultLock(true)")
        await go(pg, "vault")
        check(await pg.locator("[data-vt='unlock']").count() == 1, "verrouillage automatique pris en compte")
        # suppression d'une table : statut mis à jour
        await pg.click("[data-vt='unlock']"); await pg.fill("#pp-pass", PW + "-2"); await pg.click("#pp-ok"); await pg.wait_for_selector("#pp-form", state="detached")
        await pg.click("[data-vt='del']"); await pg.click("#md-ok")
        check(await pg.locator(".vcard").count() == 0, "table supprimée du coffre")
        await go(pg, "documents")
        check("Table non conservée sur l'appareil" in await pg.inner_text("#doc-list"), "statut du document mis à jour")
        # ---- D. Sécurité et confidentialité
        await go(pg, "security")
        await pg.uncheck("#sec-hist")
        before = await pg.evaluate("JSON.parse(localStorage.getItem('anonyx_history_v1')||'[]').length")
        await process(pg)
        after = await pg.evaluate("JSON.parse(localStorage.getItem('anonyx_history_v1')||'[]').length")
        check(before == after, "historique désactivé : rien de nouveau n'est conservé")
        await go(pg, "security"); await pg.check("#sec-hist"); await pg.check("#sec-names")
        await process(pg)
        await go(pg, "documents")
        check("texte" in (await pg.inner_text("#doc-list")).lower(), "noms de fichiers conservés seulement si l'option est activée")
        await go(pg, "security")
        await pg.click("[data-sec='wipe']"); await pg.click("#md-ok")
        check(await pg.evaluate("localStorage.length") <= 1, "effacement complet des données locales")
        await ctx.close()
        # ---- E. Migration des anciennes tables en clair
        ctx, pg = await new_page(b, errs)
        await pg.goto(URL)
        legacy = [{"format": "anonymiseur-v1", "id": "mold1", "created": "2026-01-01T00:00:00.000Z", "document": "ancien", "entries": [{"label": "Société A", "type": "org", "values": ["Alpha Conseil SARL"]}]}]
        await pg.evaluate("t => localStorage.setItem('anonymiseur_tables_v1', JSON.stringify(t))", legacy)
        await go(pg, "vault")
        check("sans chiffrement" in await pg.inner_text("#vault-body"), "tables non chiffrées signalées")
        await pg.click("[data-vt='create']"); await make_vault(pg)
        check(await pg.evaluate("localStorage.getItem('anonymiseur_tables_v1')") is None, "anciennes tables supprimées du stockage en clair")
        check(await pg.locator(".vcard").count() == 1, "ancienne table migrée dans le coffre")
        ls = await pg.evaluate("JSON.stringify(Object.entries(localStorage))")
        check("Alpha" not in ls, "table migrée chiffrée")
        await ctx.close()
        # ---- F. Mobile
        ctx, pg = await new_page(b, errs, {"width": 390, "height": 844})
        await pg.goto(URL); await pg.wait_for_selector(".view:not([hidden])")
        check(await pg.locator(".side").is_hidden() and await pg.locator(".tabbar").is_visible() and await pg.locator(".topbar").is_visible(), "navigation mobile (barre du bas)")
        check(await pg.locator("#tabbar > *").count() == 5, "5 entrées dans la barre mobile")
        await pg.click("#more-btn")
        check(await pg.locator("#sheet").is_visible() and "Restauration" in await pg.inner_text("#sheet"), "menu « Plus »")
        await pg.click("#sheet a[data-nav='security']")
        await pg.wait_for_selector("#sheet", state="hidden", timeout=3000)
        check(await pg.locator("#sheet").is_hidden(), "menu refermé après choix")
        for v in ["dashboard", "anonymize", "restore", "documents", "vault", "activity", "security", "plans", "profile"]:
            await go(pg, v)
            ov = await pg.evaluate("document.documentElement.scrollWidth - window.innerWidth")
            check(ov <= 0, f"pas de défilement horizontal sur « {v} » (390 px)")
        for lang in ["en", "fr"]:
            await pg.click(f".topbar [data-lang='{lang}']")
        await ctx.close()
        # ---- G. Installation et hors ligne
        ctx, pg = await new_page(b, errs)
        reqs = []
        pg.on("request", lambda r: reqs.append(r.url))
        await pg.goto(URL)
        check(await pg.evaluate("navigator.serviceWorker.ready.then(r => !!r.active)"), "service worker actif")
        m = await (await ctx.request.get(f"http://localhost:{PORT}/manifest.webmanifest")).json()
        check(m["name"] == "ANONYX" and {i["sizes"] for i in m["icons"]} == {"192x192", "512x512"}, "manifeste ANONYX")
        await pg.reload(); await ctx.set_offline(True); await pg.reload()
        check("ANONYX" in await pg.title(), "application disponible hors ligne")
        await process(pg)
        check("Société A" in await pg.inner_text("#preview"), "traitement hors ligne")
        ext = [u for u in reqs if not u.startswith(f"http://localhost:{PORT}") and not u.startswith("data:") and not u.startswith("blob:")]
        check(ext == [], "aucune requête externe : " + str(ext))
        await ctx.set_offline(False)
        await go(pg, "security"); await pg.click("[data-sec='cache']"); await pg.wait_for_selector("#m-sec.show")
        check("Cache vidé" in await pg.inner_text("#m-sec"), "cache hors ligne vidé à la demande")
        await ctx.close()
        check(errs == [], "aucune erreur de console : " + str(errs))
        await b.close()
asyncio.run(main())
srv.terminate()
sys.exit(1 if fails else 0)
